/**
 * Ключ идемпотентности одного списания за кадр. Чистая функция без импортов:
 * тестируется напрямую, без моков Supabase/сессии.
 *
 * До фикса ref строился как `${walletRef}:${shotId}` и не менялся между
 * попытками: POST /api/promo/shot, retryPromoShotAction и editPromoShotAction
 * при повторе видели тот же самый ref первой попытки. consume_ai_units
 * трактует такое совпадение как replay (двойной клик по кнопке) и не списывает
 * второй раз - ровно то поведение, которое нужно для честного двойного клика,
 * но которое отдаёт кадр бесплатно при «Повторить»: провайдер рисует заново
 * (деньги за первую попытку уже вернулись через release_ai_units), а
 * consume_ai_units молча пропускает списание, решив, что это тот же вызов.
 *
 * Номер попытки (retries) в ref чинит это: у каждой попытки свой ref, и
 * списание происходит каждый раз заново. Настоящий двойной клик по ОДНОЙ и
 * той же попытке (одинаковый retries) по-прежнему совпадает по ref и остаётся
 * бесплатным идемпотентным повтором - это ровно то, что и должно быть.
 */
export function shotSpendRef(walletRef: string, shotId: string, retries: number): string {
  return `${walletRef}:${shotId}:${retries}`
}
